@pytest.mark.parametrize(("domain", "want", "q"), CASES)
def test_cross_domain_tier(domain: str, want: str, q: str):
    got = classify(q)
    assert got.tier == want, (
        f"[{domain}]「{q}」判成 {got.tier}，应为 {want}；"
        f"命中理由={got.reasons}"
    )


def test_domain_coverage_complete():
    """11 个领域每个都要有用例，防止以后加规则时只测熟悉的领域。"""
    domains = {c[0] for c in CASES}
    required = {"执法", "督察", "环评", "排污许可", "在线监测", "监测",
                "固废", "大气溯源", "水环境", "土壤", "核与辐射"}
    assert required <= domains, f"缺少领域用例: {required - domains}"


def test_all_three_tiers_present_per_axis():
    """每一档都要有足够样本，避免规则偏向某一档。"""
    from collections import Counter
    c = Counter(w for _, w, _ in CASES)
    assert all(c[t] >= 8 for t in ("brief", "analysis", "formal")), c
