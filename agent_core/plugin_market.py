import json
import uuid
import logging
import shutil
from pathlib import Path
from datetime import datetime

logger = logging.getLogger("plugin_market")
ROOT = Path(__file__).resolve().parent.parent
MARKET_DIR = ROOT / "memory-tree" / "data" / "market"
MARKET_DIR.mkdir(parents=True, exist_ok=True)
PLUGINS_DIR = ROOT / "plugins"
PLUGINS_DIR.mkdir(parents=True, exist_ok=True)


class PluginMarket:
    """插件市场——搜索/安装/评分/社区"""

    def __init__(self):
        self._local_db = MARKET_DIR / "registry.json"
        self._plugins: dict[str, dict] = {}
        self._load()

    def _load(self):
        if self._local_db.exists():
            try: self._plugins = json.loads(self._local_db.read_text("utf-8", errors="replace"))
            except Exception: pass

    def _save(self):
        self._local_db.write_text(json.dumps(self._plugins, ensure_ascii=False, indent=2), encoding="utf-8")

    def publish(self, plugin_data: dict) -> str:
        """发布插件到本地市场"""
        pid = f"plugin_{uuid.uuid4().hex[:8]}"
        plugin = {"id": pid, "name": plugin_data.get("name", "unnamed"),
                  "version": plugin_data.get("version", "0.1.0"),
                  "description": plugin_data.get("description", ""),
                  "author": plugin_data.get("author", "anonymous"),
                  "category": plugin_data.get("category", "general"),
                  "rating": 0.0, "downloads": 0, "installed": 0,
                  "published_at": datetime.now().isoformat(),
                  "updated_at": datetime.now().isoformat(),
                  "files": plugin_data.get("files", []),
                  "dependencies": plugin_data.get("dependencies", []),
                  "eco_version": plugin_data.get("eco_version", ">=3.0.0")}
        self._plugins[pid] = plugin
        self._save()
        return pid

    def search(self, query: str, category: str = "") -> list[dict]:
        """搜索插件"""
        q = query.lower(); results = []
        for p in self._plugins.values():
            if category and p["category"] != category: continue
            if q in p["name"].lower() or q in p["description"].lower():
                results.append({k: p[k] for k in ["id","name","version","description","author","category","rating","downloads"]})
        return sorted(results, key=lambda x: -x["rating"])[:20]

    def install(self, plugin_id: str) -> dict:
        """安装插件"""
        plugin = self._plugins.get(plugin_id)
        if not plugin: return {"success": False, "error": "插件不存在"}
        target = PLUGINS_DIR / plugin_id
        target.mkdir(parents=True, exist_ok=True)
        # 写插件元数据
        (target / "plugin.json").write_text(json.dumps(plugin, ensure_ascii=False, indent=2), encoding="utf-8")
        # 写占位实现
        (target / "__init__.py").write_text(f"# {plugin['name']} v{plugin['version']}\n# Auto-generated by PluginMarket\n", encoding="utf-8")
        plugin["installed"] += 1; plugin["downloads"] += 1; self._save()
        return {"success": True, "plugin_id": plugin_id, "path": str(target)}

    def uninstall(self, plugin_id: str) -> dict:
        target = PLUGINS_DIR / plugin_id
        if target.exists(): shutil.rmtree(target)
        return {"success": True, "plugin_id": plugin_id}

    def rate(self, plugin_id: str, rating: float) -> dict:
        plugin = self._plugins.get(plugin_id)
        if not plugin: return {"success": False, "error": "不存在"}
        plugin["rating"] = round((plugin["rating"] * plugin["downloads"] + rating) / (plugin["downloads"] + 1), 1)
        plugin["downloads"] += 1; self._save()
        return {"success": True, "new_rating": plugin["rating"]}

    def list_installed(self) -> list[dict]:
        results = []
        for d in PLUGINS_DIR.iterdir():
            if d.is_dir() and (d / "plugin.json").exists():
                try: results.append(json.loads((d / "plugin.json").read_text("utf-8")))
                except Exception: pass
        return results

    def get_stats(self) -> dict:
        by_cat = {}
        for p in self._plugins.values(): by_cat[p["category"]] = by_cat.get(p["category"], 0) + 1
        return {"total": len(self._plugins), "installed": len(self.list_installed()),
                "by_category": by_cat, "avg_rating": round(sum(p["rating"] for p in self._plugins.values())/max(len(self._plugins),1), 1)}


