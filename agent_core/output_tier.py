    "① 结论：先给判断，一到两句说清。\n"
    "② 依据：每条依据标出处（法条精确到条款项，数据标站点与时间）。\n"
    "③ 方法：说明判定口径（用了哪个标准、怎么比对、有无折算）。\n"
    "④ 待确认：把不确定的、缺数据的、需要现场核实的单独列出。\n"
    "禁止把推测写进「结论」或「依据」——推测一律进「待确认」。"
